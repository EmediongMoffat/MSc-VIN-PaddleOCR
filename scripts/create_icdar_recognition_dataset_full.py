import os
import re
from pathlib import Path

import cv2
import numpy as np


# -----------------------------------------------------------------------------
# Paths
# -----------------------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parent.parent
DATASET_ROOT = PROJECT_ROOT / "train_data" / "ic15_data"

IMAGE_DIR = DATASET_ROOT / "test"
ANNOTATION_DIR = DATASET_ROOT / "test_gt"

OUTPUT_DIR = DATASET_ROOT / "rec_test" / "full"
LABEL_PATH = DATASET_ROOT / "rec_gt_generated.txt"


# -----------------------------------------------------------------------------
# Helper functions
# -----------------------------------------------------------------------------

def natural_sort_key(path):
    """Sort img_1, img_2, ..., img_10 in numerical order."""
    return [
        int(part) if part.isdigit() else part.lower()
        for part in re.split(r"(\d+)", path.name)
    ]


def parse_annotation_line(line):
    """
    Parse one ICDAR 2015 annotation line.

    Expected format:
    x1,y1,x2,y2,x3,y3,x4,y4,text

    split(',', 8) is used so commas inside the transcription are preserved.
    """
    parts = line.strip().split(",", 8)

    if len(parts) < 9:
        return None, None

    try:
        coords = [float(value) for value in parts[:8]]
    except ValueError:
        return None, None

    text = parts[8].strip()

    points = np.array(
        [
            [coords[0], coords[1]],
            [coords[2], coords[3]],
            [coords[4], coords[5]],
            [coords[6], coords[7]],
        ],
        dtype=np.float32,
    )

    return points, text


def order_points(points):
    """
    Arrange four polygon points in this order:

    top-left
    top-right
    bottom-right
    bottom-left
    """
    rect = np.zeros((4, 2), dtype=np.float32)

    point_sum = points.sum(axis=1)
    point_diff = np.diff(points, axis=1).reshape(-1)

    rect[0] = points[np.argmin(point_sum)]
    rect[2] = points[np.argmax(point_sum)]

    rect[1] = points[np.argmin(point_diff)]
    rect[3] = points[np.argmax(point_diff)]

    return rect


def perspective_crop(image, points):
    """Rectify a four-corner text region using perspective transformation."""
    if points.shape != (4, 2):
        return None

    if not np.all(np.isfinite(points)):
        return None

    rect = order_points(points)

    top_left, top_right, bottom_right, bottom_left = rect

    width_top = np.linalg.norm(top_right - top_left)
    width_bottom = np.linalg.norm(bottom_right - bottom_left)

    height_right = np.linalg.norm(bottom_right - top_right)
    height_left = np.linalg.norm(bottom_left - top_left)

    width = int(round(max(width_top, width_bottom)))
    height = int(round(max(height_right, height_left)))

    if width < 2 or height < 2:
        return None

    destination = np.array(
        [
            [0, 0],
            [width - 1, 0],
            [width - 1, height - 1],
            [0, height - 1],
        ],
        dtype=np.float32,
    )

    transform = cv2.getPerspectiveTransform(rect, destination)

    crop = cv2.warpPerspective(
        image,
        transform,
        (width, height),
    )

    if crop is None or crop.size == 0:
        return None

    return crop


# -----------------------------------------------------------------------------
# Main conversion
# -----------------------------------------------------------------------------

def main():

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    # Remove crops generated by an earlier run so that images and labels
    # cannot become mismatched.
    for old_crop in OUTPUT_DIR.glob("word_*.png"):
        old_crop.unlink()

    image_files = sorted(
        IMAGE_DIR.glob("img_*.jpg"),
        key=natural_sort_key,
    )

    global_word_number = 1

    scene_images_processed = 0
    valid_word_crops = 0
    hash_regions_skipped = 0
    invalid_regions_skipped = 0

    label_lines = []

    for image_path in image_files:

        scene_images_processed += 1

        image = cv2.imread(str(image_path))

        if image is None:
            print(f"WARNING: Could not read image: {image_path}")
            continue

        annotation_path = (
            ANNOTATION_DIR
            / f"gt_{image_path.stem}.txt"
        )

        if not annotation_path.exists():
            print(
                f"WARNING: Annotation not found for "
                f"{image_path.name}"
            )
            continue

        try:
            annotation_lines = annotation_path.read_text(
                encoding="utf-8-sig",
                errors="ignore",
            ).splitlines()

        except Exception as error:
            print(
                f"WARNING: Could not read {annotation_path}: "
                f"{error}"
            )
            continue

        for line in annotation_lines:

            if not line.strip():
                continue

            points, text = parse_annotation_line(line)

            if points is None or text is None:
                invalid_regions_skipped += 1
                continue

            text = text.strip()

            # ICDAR uses ### for text regions that should not be evaluated.
            if text == "###":
                hash_regions_skipped += 1
                continue

            if not text:
                invalid_regions_skipped += 1
                continue

            crop = perspective_crop(image, points)

            if crop is None:
                invalid_regions_skipped += 1
                continue

            crop_height, crop_width = crop.shape[:2]

            if crop_width < 2 or crop_height < 2:
                invalid_regions_skipped += 1
                continue

            filename = f"word_{global_word_number:06d}.png"

            output_path = OUTPUT_DIR / filename

            saved = cv2.imwrite(
                str(output_path),
                crop,
            )

            if not saved:
                print(
                    f"WARNING: Failed to save {output_path}"
                )
                invalid_regions_skipped += 1
                continue

            # IMPORTANT:
            # The label is created only AFTER the crop has been
            # successfully saved. This keeps images and labels aligned.
            relative_path = (
                Path("rec_test")
                / "full"
                / filename
            )

            label_lines.append(
                f"{relative_path.as_posix()}\t{text}"
            )

            valid_word_crops += 1
            global_word_number += 1

    # Write ground-truth file.
    with LABEL_PATH.open(
        "w",
        encoding="utf-8",
    ) as label_file:

        label_file.write(
            "\n".join(label_lines)
        )

        if label_lines:
            label_file.write("\n")

    # -------------------------------------------------------------------------
    # Summary
    # -------------------------------------------------------------------------

    print()
    print("ICDAR recognition dataset conversion complete")
    print("--------------------------------------------")
    print(
        f"Scene images processed: "
        f"{scene_images_processed}"
    )
    print(
        f"Valid word crops generated: "
        f"{valid_word_crops}"
    )
    print(
        f"### regions skipped: "
        f"{hash_regions_skipped}"
    )
    print(
        f"Invalid regions skipped: "
        f"{invalid_regions_skipped}"
    )
    print(
        f"Generated label file: "
        f"{LABEL_PATH}"
    )


if __name__ == "__main__":
    main()